test('a hidden tab accrues no playback time and static view preserves the sampled frame', async ({page}) => {
  await openStep(page)
  await page.clock.install()
  const panel = page.getByTestId('etc-panel-a')
  const progress = panel.getByRole('progressbar')
  const elapsed = () => numberAttribute(progress, 'value')
  await page.getByRole('combobox',{name:'조건 A 처리'}).selectOption('leak')
  await expect.poll(elapsed).toBeGreaterThan(0)
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', {configurable:true, value:true})
    document.dispatchEvent(new Event('visibilitychange'))
  })
  const before = await elapsed()
  await page.clock.fastForward(30000)
  expect(await elapsed()).toBe(before)
  await page.evaluate(() => {
    Reflect.deleteProperty(document, 'hidden')
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect.poll(elapsed).toBeGreaterThan(before)
  expect(await elapsed() - before).toBeLessThan(1)
  await page.getByRole('button',{name:'정적 보기',exact:true}).click()
  const held = await elapsed()
  const canvas = panel.locator('canvas')
  const angle = await canvas.getAttribute('data-rotation')
  await page.clock.fastForward(10000)
  await expect(canvas).toHaveAttribute('data-rotation', angle!)
  expect(await elapsed()).toBe(held)
  await page.getByRole('button',{name:'3D 보기',exact:true}).click()
  await expect.poll(elapsed).toBeGreaterThan(held)
  expect(await elapsed() - held).toBeLessThan(1)
})
